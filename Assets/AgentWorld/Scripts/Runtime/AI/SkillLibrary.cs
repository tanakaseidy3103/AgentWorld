using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading;

namespace AgentWorld
{
    /// Read-only views of the skill registry for the Skill Library panel, the terminal and the docs,
    /// plus a safe tester that goes through the same validator the model's plans go through.
    public static class SkillLibrary
    {
        /// Why an agent can or cannot use a skill (registry roles first, then agents.json).
        public static string Availability(Skill s, string role) =>
            !s.Roles.Contains(role) ? $"no: role '{role}' is not allowed to hold this skill"
            : AgentConfigs.Has(role, s.Id) ? "yes"
            : "no: allowed for the role, but not enabled in agents.json";

        // --- Safe testing -----------------------------------------------------------

        /// Dry run: parses one action (or a whole plan) and checks registry, permissions and world.
        /// Executes nothing. Returns every validation error; empty means the plan would run.
        public static List<string> Check(string role, string json, ICollection<string> locations, out AgentPlan plan)
        {
            var raw = (json ?? "").Trim();
            if (raw.StartsWith("{") && !raw.Contains("\"actions\"")) raw = "{\"actions\":[" + raw + "]}";
            plan = PlanValidator.Parse(raw, out var parseError);
            if (plan == null) return new List<string> { parseError + " (expected e.g. {\"type\":\"count_people\",\"target\":\"lab\"})" };
            var errors = PlanValidator.Validate(plan, locations, role);
            var types = plan.actions.Select(a => a?.type).ToList();
            foreach (var idea in SkillRegistry.DocumentationOnly.Where(d => types.Contains(d.Id)))
                errors.Add($"'{idea.Id}' is a documentation-only example ({idea.Missing}); it is not registered");
            if (errors.Any(e => e.Contains("invalid location"))) errors.Add("valid location ids: " + string.Join(", ", locations.OrderBy(l => l)));
            return errors;
        }

        public static List<string> Check(NpcAgent agent, string json, out AgentPlan plan) =>
            Check(agent.agentRole, json, Landmark.All.Select(l => l.id).ToList(), out plan);

        /// Validates first, then runs the actions on the agent through the normal executors (no LLM involved).
        public static bool Run(NpcAgent agent, string json, Action<string> output, out List<string> errors)
        {
            errors = Check(agent, json, out var plan);
            if (errors.Count == 0 && MissionControl.Running) errors.Add("a mission is running; stop it first (mission stop)");
            if (errors.Count == 0 && agent.Ai.Busy) errors.Add($"{agent.displayName} is busy; use 'agent stop {agent.id}'");
            if (errors.Count > 0) return false;
            _ = agent.Ai.Perform("skill test: " + string.Join(", ", plan.actions), plan.actions, output, CancellationToken.None);
            return true;
        }

        // --- Generated documentation ------------------------------------------------

        public const string DocsBegin = "<!-- SKILLS:BEGIN (generated by AgentWorld > Update Skill Docs; do not edit) -->";
        public const string DocsEnd = "<!-- SKILLS:END -->";

        /// Markdown reference of every registered skill and who may use it (from the registry and agents.json).
        public static string Markdown()
        {
            var agents = AgentConfigs.Current.agents;
            var sb = new StringBuilder();
            sb.Append("| Skill | Origin | Parameters | Roles allowed | Enabled for | Safety |\n|---|---|---|---|---|---|\n");
            foreach (var s in SkillRegistry.All)
            {
                var enabled = agents.Where(a => a.skills.Contains(s.Id)).Select(a => a.id).ToList();
                sb.Append($"| `{s.Id}` {s.Name}: {s.Description} | {s.Origin} | {string.Join("; ", s.Parameters)} | {string.Join(", ", s.Roles)} | {(enabled.Count == 0 ? "nobody" : string.Join(", ", enabled))} | {s.Safety} |\n");
            }
            sb.Append("\nDocumentation-only examples (not registered; agents cannot use them and plans naming them are rejected):\n\n");
            foreach (var d in SkillRegistry.DocumentationOnly) sb.Append($"- `{d.Id}`: {d.Description} Not implemented: {d.Missing}.\n");
            return sb.ToString();
        }

        /// Replaces the generated block between the markers; returns null if the markers are missing.
        public static string ReplaceDocs(string guide)
        {
            int a = guide.IndexOf(DocsBegin, StringComparison.Ordinal), b = guide.IndexOf(DocsEnd, StringComparison.Ordinal);
            if (a < 0 || b < a) return null;
            return guide.Substring(0, a + DocsBegin.Length) + "\n" + Markdown() + guide.Substring(b);
        }
    }
}

namespace AgentWorld
{
    /// What a result-reporting skill actually returned in the current task (never from memory or earlier runs).
    public class SkillResult
    {
        public string SkillId, Text;
    }

    /// Separates tool execution from reporting: in a plan that measures something, a speak action may not state
    /// a result the model predicted. Before any measurement it is skipped; after one it is replaced by the
    /// SkillResult Unity returned.
    public static class ResultReporting
    {
        static readonly Regex Claim = new Regex(@"\d|\b(zero|one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve|nobody|no one|none|empty)\b", RegexOptions.IgnoreCase);

        public static bool ClaimsResult(string message) => Claim.IsMatch(message ?? "");

        /// The message to speak, or null to skip it. latest must come from the current task only.
        public static string Rewrite(string message, SkillResult latest) =>
            !ClaimsResult(message) ? message : latest == null ? null : latest.Text.Length > 200 ? latest.Text.Substring(0, 200) : latest.Text;
    }
}
